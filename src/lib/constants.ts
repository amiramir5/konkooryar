export function getGoftarsForChapter(chapter: string): string[] {
  if (!chapter) return [];
  // Match by exact key or substring
  const exact = BIOLOGY_GOFTARS[chapter];
  if (exact) return exact;
  const foundKey = Object.keys(BIOLOGY_GOFTARS).find((k) => k.includes(chapter) || chapter.includes(k.replace(/^(دهم|یازدهم|دوازدهم):\s*/, '')));
  return foundKey ? BIOLOGY_GOFTARS[foundKey] : [];
}

